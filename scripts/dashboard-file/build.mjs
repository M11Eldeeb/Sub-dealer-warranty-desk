// Builds the two pieces the interactive dashboard file is made of (the page's script and its styles) and writes them to
// lib/generated/dashboard-assets.js. Runs before `next dev` and `next build`.
import { build } from "esbuild";
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const HERE = path.join(ROOT, "scripts/dashboard-file");
const OUT_DIR = path.join(ROOT, "lib/generated");
mkdirSync(OUT_DIR, { recursive: true });

// 1. the script: the dashboard page with React, framer-motion and the icons inside
const swap = {
  "next/link": path.join(HERE, "link-stub.js"),
  [path.join(ROOT, "components/DailyWidgets")]: path.join(HERE, "widgets-stub.js"),
};
const result = await build({
  entryPoints: [path.join(HERE, "entry.js")],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: ["es2020"],
  jsx: "automatic",
  loader: { ".js": "jsx" },
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  logLevel: "warning",
  plugins: [
    {
      name: "site-paths",
      setup(b) {
        b.onResolve({ filter: /^next\/link$/ }, () => ({ path: swap["next/link"] }));
        b.onResolve({ filter: /^@\// }, async (args) => {
          const target = path.join(ROOT, args.path.slice(2));
          if (swap[target]) return { path: swap[target] };
          return b.resolve("./" + args.path.slice(2), { resolveDir: ROOT, kind: args.kind });
        });
      },
    },
  ],
});
const js = result.outputFiles[0].text;

// 2. the styles: the site's own Tailwind build
const cssFile = path.join(OUT_DIR, "dashboard.css");
const tw = spawnSync(process.execPath, [require.resolve("tailwindcss/lib/cli.js"), "-i", path.join(ROOT, "app/globals.css"), "-o", cssFile, "--minify"], { cwd: ROOT, encoding: "utf8" });
if (tw.status !== 0) {
  console.error(tw.stdout, tw.stderr);
  throw new Error("Tailwind could not build the styles for the dashboard file.");
}
const css = readFileSync(cssFile, "utf8");
const logo = `data:image/png;base64,${readFileSync(path.join(ROOT, "public/mg-logo.png")).toString("base64")}`;
rmSync(cssFile);

writeFileSync(
  path.join(OUT_DIR, "dashboard-assets.js"),
  `// GENERATED by scripts/dashboard-file/build.mjs - do not edit, do not commit.\nexport const DASHBOARD_JS = ${JSON.stringify(js)};\nexport const DASHBOARD_CSS = ${JSON.stringify(css)};\nexport const DASHBOARD_LOGO = ${JSON.stringify(logo)};\n`
);
console.log(`dashboard file assets: script ${(js.length / 1024).toFixed(0)} KB, styles ${(css.length / 1024).toFixed(0)} KB`);
